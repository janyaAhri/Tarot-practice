const split = (s) => s.split(", ").map((t) => t.trim()).filter(Boolean);

const CARDS = [];

MAJOR_DATA.forEach(([n, en, th, up, rev]) => {
  CARDS.push({
    id: "major-" + n, suit: "major", num: n, label: toRoman(n),
    en, th, up: split(up), rev: split(rev),
  });
});

Object.keys(MINOR_DATA).forEach((suit) => {
  MINOR_DATA[suit].forEach((pair, i) => {
    const [up, rev] = pair.split("|");
    CARDS.push({
      id: suit + "-" + i, suit, num: i + 1, label: RANK_SHORT[i],
      en: RANK_EN[i] + " of " + capital(suit),
      th: RANK_TH[i] + SUITS[suit].th,
      up: split(up), rev: split(rev),
    });
  });
});

function capital(s) { return s.charAt(0).toUpperCase() + s.slice(1); }

function toRoman(n) {
  if (n === 0) return "0";
  const map = [[10, "X"], [9, "IX"], [5, "V"], [4, "IV"], [1, "I"]];
  let out = "";
  for (const [v, r] of map) while (n >= v) { out += r; n -= v; }
  return out;
}
